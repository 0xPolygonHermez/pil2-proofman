//! both off the circom file.

use proofman_fields::Bn254;

/// The lanes of the state.
pub const WIDTH: usize = 5;

/// Full rounds: the first `FULL_ROUNDS / 2` and the last `FULL_ROUNDS / 2`.
pub const FULL_ROUNDS: usize = 8;

/// Partial rounds, `N_ROUNDS_P[t − 2]` of the circom template for t = 5.
pub const PARTIAL_ROUNDS: usize = 60;

/// Rounds of a permutation.
pub const ROUNDS: usize = FULL_ROUNDS + PARTIAL_ROUNDS;

/// Whether round `r` is full: S-boxes on every lane, not only on lane 0.
pub const fn is_full_round(r: usize) -> bool {
    r < FULL_ROUNDS / 2 || r >= FULL_ROUNDS / 2 + PARTIAL_ROUNDS
}

/// The element of canonical value `decimal`. Only for constant items: a wrong literal fails the
/// build.
const fn element(decimal: &str) -> Bn254 {
    match Bn254::from_decimal(decimal) {
        Some(x) => x,
        None => panic!("not a canonical decimal element of Fr"),
    }
}

